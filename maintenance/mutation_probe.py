def run_selftest(directory: Path, report_name: str, *groups: str) -> dict:
    """Runs the selftest of the tool copy in directory (all groups, or the named ones); the report, or {} when none
    was written. A timeout raises subprocess.TimeoutExpired."""
    out = directory / report_name
    command = [sys.executable, '-B', str(directory / 'tools' / 'audit_tools.py'), 'selftest', '--out', str(out)]
    for group in groups:
        command += ['--group', group]
    with open(directory / (report_name + '.txt'), 'wb') as output:
        subprocess.run(command, stdout=output, stderr=subprocess.STDOUT, timeout=SELFTEST_TIMEOUT)
    return json.loads(out.read_text(encoding='utf-8')) if out.is_file() else {}


def write_tool(directory: Path, text: str) -> None:
    (directory / 'tools').mkdir(parents=True, exist_ok=True)
    (directory / 'tools' / 'audit_tools.py').write_text(text, encoding='utf-8', newline='\n')


def run_baseline() -> dict:
    """The complete selftest of the unmutated source; stops the probe unless it reports no failed control."""
    directory = work / '_baseline'
    write_tool(directory, source)
    try:
        report = run_selftest(directory, 'selftest.json')
    except subprocess.TimeoutExpired:
        raise SystemExit(f'Baseline selftest timed out; a probe on an unknown baseline proves nothing. See {directory}')
    if not report:
        raise SystemExit(f'Baseline selftest wrote no report; a probe on a broken baseline proves nothing. See {directory}')
    failed = report['summary']['failed']
    if failed:
        raise SystemExit(f'Baseline selftest has failed controls; a probe on a failing baseline proves nothing. '
                         f'Fix them first: {failed}. See {directory}')
    return report


def verdict(name: str, baseline: dict) -> str:
    control_id, old, new = MUTANTS[name]
    platform = PLATFORMS.get(name)
    if platform and (sys.platform != 'linux' if platform == 'linux' else os.name != platform):
        return f'NOT_APPLICABLE: {platform} only ({control_id})'
    if source.count(old) != 1:
        return f'ERROR: anchor {source.count(old)}x'
    groups = {entry['id']: entry['group'] for entry in baseline['results']}
    if control_id not in groups:
        return f'ERROR: control {control_id} is not a selftest control'
    if control_id in baseline['summary']['skipped']:
        return f'NOT_APPLICABLE: control {control_id} skipped on this platform'
    target_dir = work / name
    write_tool(target_dir, source.replace(old, new))
    try:
        if not FULL:
            report = run_selftest(target_dir, 'selftest-group.json', groups[control_id])
            # a group run without a report (the mutant may have broken --group itself) proves nothing either way
            if report and control_id in report['summary']['failed']:
                return f'KILLED by {control_id}'
        report = run_selftest(target_dir, 'selftest.json')
    except subprocess.TimeoutExpired:
        return f'ERROR: timeout ({control_id})'
    if not report:
        return f'ERROR: selftest aborted without report ({control_id} not reached)'
    failed = report['summary']['failed']
    if control_id not in failed:
        return f'SURVIVED (failed: {failed})'
    return f'KILLED by {control_id}' + ('' if FULL else ' (complete selftest only)')


